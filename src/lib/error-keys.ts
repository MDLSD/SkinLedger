/**
 * Экшены и схемы валидации возвращают не текст ошибки, а ключ перевода из
 * неймспейса `errors` — язык знает только тот, кто её показывает
 * (см. `useErrorMessage` в src/i18n/error-message.ts).
 *
 * Тип намеренно широкий, а не объединение конкретных ключей: часть сообщений
 * приходит из самого zod (у полей без своего message) и ключом не является.
 */
export type ErrorKey = string;

/** Подстановки для ключей с плейсхолдерами: сколько ждать, какой лимит. */
export type ErrorValues = Record<string, string | number>;

/**
 * Сообщение, которое переводит получатель. Нужно там, где сервер отдаёт
 * не одну ошибку, а список (пометки анализа импорта, ошибки по строкам файла).
 */
export type LocalizedMessage = { key: ErrorKey; values?: ErrorValues };
